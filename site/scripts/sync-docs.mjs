import { mkdir, readdir, readFile, unlink, writeFile } from 'node:fs/promises';
import { posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { unified } from 'unified';
import remarkParse from 'remark-parse';
import remarkStringify from 'remark-stringify';
import { visit } from 'unist-util-visit';

export const guides = [
  'player-guide',
  'player-installer',
  'starter-level',
  'music',
  'thps-warehouse',
  'thps-warehouse-layout',
  'thps-warehouse-pieces',
  'thunderstore',
];
const marker = '<!-- Generated by sync-docs.mjs; edit docs/ instead. -->';
const repository = 'https://github.com/pythoninthegrass/megabonk_mods/blob/main/';

function rewriteUrl(url) {
  if (/^(?:[a-z][a-z\d+.-]*:|#|\/)/i.test(url)) return url;
  const [, path, suffix = ''] = url.match(/^([^?#]+)([?#].*)?$/) ?? [];
  if (!path) return url;
  const normalized = posix.normalize(posix.join('docs', path));
  const slug = normalized.replace(/^docs\//, '').replace(/\.md$/, '');
  if (normalized.startsWith('docs/') && guides.includes(slug)) return `/${slug}/${suffix}`;
  return repository + normalized + suffix;
}

export function transformDoc(source) {
  const title = source.match(/^# (.+)\r?\n/);
  if (!title) throw new Error('Published docs must have a leading H1');
  const processor = unified().use(remarkParse).use(remarkStringify, { bullet: '-', fences: true });
  const tree = processor.parse(source.slice(title[0].length).trimStart());
  visit(tree, (node) => {
    if (['link', 'image', 'definition'].includes(node.type)) node.url = rewriteUrl(node.url);
  });
  return `---\ntitle: ${JSON.stringify(title[1].trim())}\n---\n\n${marker}\n\n${
    processor.stringify(tree)
  }`;
}

export async function syncDocs({
  source = fileURLToPath(new URL('../../docs/', import.meta.url)),
  target = fileURLToPath(new URL('../src/content/docs/', import.meta.url)),
} = {}) {
  const pages = await Promise.all(guides.map(async (slug) => [
    `${slug}.md`,
    transformDoc(await readFile(resolve(source, `${slug}.md`), 'utf8')),
  ]));
  await mkdir(target, { recursive: true });
  for (const [name, body] of pages) {
    const path = resolve(target, name);
    let current;
    try {
      current = await readFile(path, 'utf8');
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (current !== body) await writeFile(path, body);
  }
  for (const name of await readdir(target)) {
    if (!name.endsWith('.md') || pages.some(([file]) => file === name)) continue;
    const path = resolve(target, name);
    if ((await readFile(path, 'utf8')).includes(marker)) await unlink(path);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await syncDocs();
}
