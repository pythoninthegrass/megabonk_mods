import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { guides, syncDocs, transformDoc } from '../scripts/sync-docs.mjs';

test('publication is an explicit eight-guide allowlist', () => {
  assert.equal(guides.length, 8);
  assert.ok(guides.includes('player-guide'));
  assert.ok(!guides.includes('development'));
});

test('title conversion and link rewriting preserve code and external URLs', () => {
  const output = transformDoc(
    '# A title: "quoted"\n\n[Play](./player-guide.md#installing)\n[Dev](development.md#tools)\n[Package](../pkg/README.md)\n[Anchor](#here)\n[Web](https://example.com/a.md)\n\n```md\n[Code](player-guide.md)\n```\n',
  );
  assert.ok(output.includes('title: "A title: \\"quoted\\""'));
  assert.doesNotMatch(output, /^# A title/m);
  assert.match(output, /\[Play\]\(\/player-guide\/#installing\)/);
  assert.match(
    output,
    /github.com\/pythoninthegrass\/megabonk_mods\/blob\/main\/docs\/development.md#tools/,
  );
  assert.match(output, /blob\/main\/pkg\/README.md/);
  assert.match(output, /\[Anchor\]\(#here\)/);
  assert.match(output, /https:\/\/example.com\/a.md/);
  assert.match(output, /```md\n\[Code\]\(player-guide.md\)\n```/);
});

test('reference-style links are rewritten and missing H1 fails loudly', () => {
  assert.match(
    transformDoc('# Guide\n\n[Read][guide]\n\n[guide]: music.md#playback\n'),
    /\[guide\]: \/music\/#playback/,
  );
  assert.throws(() => transformDoc('No title'), /leading H1/);
});

test('sync preserves mtimes and hand-authored index, deletes only orphaned generated pages', async () => {
  const root = await mkdtemp(join(tmpdir(), 'wiki-sync-'));
  try {
    const source = join(root, 'docs');
    const target = join(root, 'output');
    await mkdir(source);
    await mkdir(target);
    for (const slug of guides) await writeFile(join(source, `${slug}.md`), `# ${slug}\n\nBody.\n`);
    await writeFile(join(source, 'development.md'), '# Internal\n');
    await writeFile(join(target, 'index.md'), '# Wiki\n');
    await writeFile(
      join(target, 'orphan.md'),
      '<!-- Generated by sync-docs.mjs; edit docs/ instead. -->\n',
    );
    await writeFile(join(target, 'notes.md'), '# Hand authored\n');
    await syncDocs({ source, target });
    const before = (await stat(join(target, 'music.md'))).mtimeMs;
    await syncDocs({ source, target });
    assert.equal((await stat(join(target, 'music.md'))).mtimeMs, before);
    assert.equal(await readFile(join(target, 'index.md'), 'utf8'), '# Wiki\n');
    assert.equal(await readFile(join(target, 'notes.md'), 'utf8'), '# Hand authored\n');
    await assert.rejects(stat(join(target, 'orphan.md')), { code: 'ENOENT' });
    await assert.rejects(stat(join(target, 'development.md')), { code: 'ENOENT' });
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});
